/// TCH/F9.6: every 15th bit from 11.
pub(super) fn tch_f96() -> Vec<i32> {
    (0..32).map(|j| 11 + 15 * j).collect()
}

/// TCH/F14.4: offsets 1, 6, 11 and 15 of each 18 bits up to 582, then 584 and 587.
pub(super) fn tch_f144() -> Vec<i32> {
    (0..33)
        .flat_map(|block| [1, 6, 11, 15].map(|offset| 18 * block + offset))
        .filter(|&position| position <= 582)
        .chain([584, 587])
        .collect()
}

/// CS-2: every 4th bit from 15, except 39 and every 48th bit after it.
pub(super) fn cs2() -> Vec<i32> {
    (15..588)
        .step_by(4)
        .filter(|position| (position - 39) % 48 != 0)
        .collect()
}

/// CS-3: the bits from 15 to 671 that are 3 or 5 modulo 6.
pub(super) fn cs3() -> Vec<i32> {
    (15..672)
        .filter(|position| matches!(position % 6, 3 | 5))
        .collect()
}

/// TCH/HS: every 3rd bit from 1, except 286, 289 and 292.
pub(super) fn tch_hr() -> Vec<i32> {
    (1..312)
        .step_by(3)
        .filter(|position| !matches!(position, 286 | 289 | 292))
        .collect()
}

